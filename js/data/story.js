export function chLabel(ch, long = false) {
  if (ch <= 11) return long ? `第${ch}章「${CHAPTERS[ch]}」` : `第${ch}章`;
  if (ch === 12) return 'クリア後';
  if (ch <= 21) return long ? `第2部 第${ch - 12}章「${CHAPTERS[ch]}」` : `第2部 第${ch - 12}章`;
  return '第2部 クリア後';
}
