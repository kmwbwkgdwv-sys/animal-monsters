// 2Dバリューノイズ（決定論的）
function h2(x, y, seed) {
  let h = Math.imul(x, 374761393) + Math.imul(y, 668265263) + Math.imul(seed, 2147483647);
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}
export function vnoise(x, y, seed = 0) {
  const xi = Math.floor(x), yi = Math.floor(y), xf = x - xi, yf = y - yi;
  const u = xf * xf * (3 - 2 * xf), v = yf * yf * (3 - 2 * yf);
  const a = h2(xi, yi, seed), b = h2(xi + 1, yi, seed), c = h2(xi, yi + 1, seed), d = h2(xi + 1, yi + 1, seed);
  return a + (b - a) * u + (c - a) * v + (a - b - c + d) * u * v;
}
export function fbm(x, y, oct = 4, seed = 0) {
  let s = 0, amp = 0.5, f = 1, n = 0;
  for (let i = 0; i < oct; i++) { s += vnoise(x * f, y * f, seed + i * 17) * amp; n += amp; amp *= 0.5; f *= 2.03; }
  return s / n;
}
export function ridge(x, y, oct = 4, seed = 0) {
  let s = 0, amp = 0.5, f = 1, n = 0;
  for (let i = 0; i < oct; i++) { const v = 1 - Math.abs(vnoise(x * f, y * f, seed + i * 31) * 2 - 1); s += v * v * amp; n += amp; amp *= 0.5; f *= 2.1; }
  return s / n;
}
export function uid(prefix = '') {
  const c = 'abcdefghijkmnopqrstuvwxyz23456789';
  let s = prefix;
  const arr = new Uint32Array(12);
  (globalThis.crypto || window.crypto).getRandomValues(arr);
  for (let i = 0; i < 12; i++) s += c[arr[i] % c.length];
  return s;
}
